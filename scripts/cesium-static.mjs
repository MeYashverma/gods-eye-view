import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

/**
 * Cesium loads its workers, imagery approximations, widget CSS and third-party
 * WASM decoders from a static base URL at runtime (`window.CESIUM_BASE_URL`).
 * A bundler cannot inline those, so they are copied verbatim next to the
 * built app under `cesium/` — a path relative to the deployed base, which is
 * what makes `https://<owner>.github.io/<repo>/` work.
 *
 * `Cesium.js` / `index.cjs` are deliberately excluded: the app bundles Cesium
 * from `Source/`, and shipping the prebuilt UMD copies would add ~10 MB of
 * dead weight to the published site.
 */
const STATIC_DIRS = ['Workers', 'Assets', 'ThirdParty', 'Widgets'];

export function cesiumStaticAssets() {
  let outDir = 'dist';
  let root = process.cwd();
  let base = '/';

  return {
    name: 'gev:cesium-static-assets',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir || 'dist';
      root = config.root || process.cwd();
      base = config.base || '/';
    },
    async closeBundle() {
      const cesiumRoot = path.dirname(require.resolve('cesium/package.json'));
      const sourceRoot = path.join(cesiumRoot, 'Build', 'Cesium');
      const targetRoot = path.resolve(root, outDir, 'cesium');
      const copied = [];
      for (const dir of STATIC_DIRS) {
        const from = path.join(sourceRoot, dir);
        const to = path.join(targetRoot, dir);
        await fs.cp(from, to, { recursive: true, force: true });
        copied.push(dir);
      }
      console.log(`[gev] copied Cesium static assets (${copied.join(', ')}) -> ${path.relative(root, targetRoot)}`);
      await fs.writeFile(
        path.resolve(root, outDir, 'cesium-base.js'),
        cesiumBaseScript(base),
        'utf8',
      );
      console.log(`[gev] wrote cesium-base.js -> CESIUM_BASE_URL = ${base}cesium/`);
    },
  };
}

/**
 * Contents of `cesium-base.js`. Cesium reads the `CESIUM_BASE_URL` global lazily
 * inside `buildModuleUrl()`, so a plain (non-module) script that runs before the
 * app bundle is enough — and, unlike an inline `<script>` in `index.html`, it
 * survives a Content-Security-Policy without `script-src 'unsafe-inline'`.
 */
export function cesiumBaseScript(base = '/') {
  const normalized = base.endsWith('/') ? base : `${base}/`;
  return [
    '/* Generated by scripts/cesium-static.mjs — matches the deployed base path. */',
    `window.CESIUM_BASE_URL = '${normalized}cesium/';`,
    '',
  ].join('\n');
}

export { STATIC_DIRS };
