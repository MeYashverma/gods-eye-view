export function getSource(id) {
  return SOURCES[id] || null;
}

/** Flat list for the attribution popover, sorted by display name. */
export function listSources() {
  return Object.values(SOURCES).sort((a, b) => a.name.localeCompare(b.name));
}

/** Sources the app reaches without any user configuration. */
export function keylessSources() {
  return listSources().filter(
    (source) =>
      !['cesium-ion', 'google-tiles', 'mapillary', 'aisstream', 'firms'].includes(source.id),
  );
}
